const assert = require('node:assert/strict');
const Intel = require('../assets/intelligence.js');
assert.equal(Intel.storeServiceCategory({retailer:'Sunglass Hut'}), 'unverified');
assert.equal(Intel.storeServiceCategory({business_type:'Sunglasses retail'}), 'retail');
assert.equal(Intel.storeServiceCategory({services:'Eye examinations; prescription eyewear'}), 'optometry');
assert.equal(Intel.storeServiceCategory({business_type:'Permanent retail optometry'}), 'optometry');
assert.equal(Intel.storeServiceCategory({business_type:'Sunglasses retail',services:'No eye tests'}), 'retail');
assert.equal(Intel.storeServiceCategory({services:'Collect & Return'}), 'unverified');
assert.equal(Intel.storeServiceCategory({services:'Prescription eyewear'}), 'unverified');
assert.equal(Intel.storeServiceCategory({business_type:'Eyewear retail',services:'Fitting service; Simple repair'}), 'retail');
assert.deepEqual(Intel.sanitiseShareState({filters:{service:'retail'}}).filters.service, ['retail']);
assert.deepEqual(Intel.sanitiseShareState({filters:{service:'bad-value'}}).filters.service, []);
assert.deepEqual(Intel.sanitiseShareState({filters:{}}).filters.service, []);
console.log('Store service filter tests passed');

assert.deepEqual(Intel.normaliseStoreSelection(['retail','optometry','retail','invalid'],'service'), ['optometry','retail']);
assert.deepEqual(Intel.normaliseStoreSelection('Uncertain','location'), ['Uncertain']);
assert.deepEqual(Intel.normaliseStoreSelection(['Closed','Active'],'status'), ['Active']);
const filters = {retailers:new Set(['OPSM']), location:['Uncertain','High Street'], service:['optometry','unverified'], status:['Active','Unknown']};
const store = {retailer:'OPSM',status:'Active',location_type:'Shopping Centre',services:'Eye examinations'};
assert.deepEqual(Intel.storeFilterExclusions(store,filters), ['Place type']);
assert.deepEqual(Intel.storeFilterExclusions({...store,location_type:'High Street'},filters), []);
assert.deepEqual(Intel.storeFilterExclusions({...store,location_type:'High Street',business_type:'Sunglasses retail',services:''},filters), ['Store services']);
assert.deepEqual(Intel.storeFilterExclusions(store,{...filters,location:[],service:[],status:[]}), []);
const shared=Intel.sanitiseShareState({filters});
assert.deepEqual(shared.filters.location,['High Street','Uncertain']);
assert.deepEqual(shared.filters.service,filters.service);
assert.deepEqual(Intel.sanitiseShareState({filters:shared.filters}),shared);
console.log('Multi-select compatibility and exclusion reasons passed');
