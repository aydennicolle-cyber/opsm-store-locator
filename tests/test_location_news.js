const assert = require('node:assert/strict');
const news = require('../assets/location-news.js');
const v = (date, recorded, title='Story') => ({published_on:date,recorded_at:recorded,title,statements:[{text:'Reported',kind:'source_report'}],sources:[{url:'https://example.com',title:'Source'}],metrics:[],timing:'',uncertainty:'',date_basis:''});
const event = (id, date, relation, parent=null) => ({event_id:id,parent_event_id:parent,kind:'news',scope:'location',relations:[relation],versions:[v(date,'2026-10-21')]});
const direct={entity_id:'place-a',kind:'direct_place',label:'Place',basis:'Named place',distance_km:null};
const area={entity_id:'store-a',kind:'area_store',label:'Nearby',basis:'Approximate point; not membership',distance_km:0.4};
const data={events:[event('old','2024',direct),event('recent','2026-10',direct),event('unknown',null,area)],checks:[]};
data.events[0].versions[0].recorded_at='2026-10-23';
assert.deepEqual(news.select(data,{place_id:'place-a'}).map(x=>x.event.event_id),['recent','old']);
assert.equal(news.select(data,{store_id:'store-a'})[0].area,true);
assert.equal(news.select(data,{all:true}).find(x=>x.event.event_id==='unknown').area,true);
assert.equal(news.select(data,{place_id:'other'}).length,0);
data.events.push(event('child','2026-10',direct,'recent'));
assert(!news.select(data,{place_id:'place-a'}).some(x=>x.event.event_id==='recent'));
assert(news.select(data,{all:true}).some(x=>x.event.event_id==='recent'));
data.events[0].versions[0].title='<img onerror="bad">';
assert(news.render(data,{all:true}).includes('&lt;img'));
assert(!news.render(data,{all:true}).includes('<img onerror'));
assert(news.render(null).includes('could not be loaded'));
assert(news.render({events:[],checks:[]}).includes('does not establish'));
assert.equal(news.dateLabel('2024'),'2024');
// An article can support several independently maintained store histories.
const article={source_id:'article',url:'https://example.com/news/centre-update',title:'Centre additions | Local Paper'};
const opening=(id,text,relation=direct,date='2026-10-12')=>{
  const e=event(id,date,relation);
  e.versions[0].sources=[article];
  e.versions[0].title=text.split(' as ')[0];
  e.versions[0].statements=[{text,kind:'source_report',source_ids:['article']}];
  return e;
};
const a=opening('a','Local Paper reported Alpha as open.');
const b=opening('b','Local Paper described Beta as coming soon.');
b.versions[0].sources.push({source_id:'locator',url:'https://beta.example/shops/centre',title:'Beta locator'});
a.versions.push({...v('2025-11-01','2025-11-02','Earlier proposal'),revision_id:'earlier'});
const groupedData={events:[a,b],checks:[{source_url:article.url,status:'blocked',attempted_at:'2026-10-23',note:'Unavailable',last_success_at:'2026-10-21'}]};
const original=JSON.stringify(groupedData);
const groups=news.groupStories(news.select(groupedData,{place_id:'place-a'}));
assert.equal(groups.length,1);
assert.equal(groups[0].members.length,2);
assert.equal(groups[0].source.url,article.url);
const groupedHtml=news.render(groupedData,{place_id:'place-a'});
assert.equal((groupedHtml.match(/<article /g)||[]).length,1);
assert(groupedHtml.includes('<strong>Alpha</strong> — open.'));
assert(groupedHtml.includes('<strong>Beta</strong> — coming soon.'));
assert(groupedHtml.includes('Earlier proposal'));
assert(groupedHtml.includes('https://beta.example/shops/centre'));
assert(groupedHtml.includes('Source check blocked'));
assert(groupedHtml.includes('data-news-expanded="false"'));
assert(news.render(groupedData,{all:true}).includes('data-news-expanded="true"'));
assert.equal(JSON.stringify(groupedData),original,'Rendering must not mutate evidence or event identities');
const separate=(other)=>news.groupStories(news.select({events:[a,other]},{all:true})).length;
assert.equal(separate(opening('later','Same article, different date',direct,'2026-10-13')),2);
assert.equal(separate(opening('unknown','Unknown date',direct,null)),2);
assert.equal(separate(opening('nearby','Area context',{...direct,kind:'area_place'})),2);
assert.equal(separate(opening('other','Other centre',{...direct,entity_id:'place-b'})),2);
const observed=opening('observed','Record added'); observed.versions[0].statements[0].kind='dataset_observation';
assert.equal(separate(observed),2);
const metric=opening('metric','Metric'); metric.versions[0].metrics=[{name:'Footfall'}];
assert.equal(separate(metric),2);
const changed=opening('changed','Reported earlier'); changed.versions.push({...changed.versions[0],published_on:'2026-10-15',recorded_at:'2026-10-24'});
assert.equal(separate(changed),2,'A subsequent dated update must leave the old article group');
assert.deepEqual(news.compactHeading(b.versions[0]),{title:'Local Paper described Beta as coming soon.',body:''});
console.log('Location news: grouping boundaries, preserved history/status/sources, compact display, date ordering, geography, escaping and empty/error states passed');
